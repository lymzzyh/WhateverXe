// Local descriptor adaptation for one qualified, already-validated code page.
// The reference remains private Apple payload data and is not an upstream asset.
#pragma once
#include "kern_uhd770_page.hpp"
#include "kern_local_video_abi.hpp"
#include "kern_local_gva.hpp"
namespace LocalTahoeABI {
static constexpr size_t PageSize=4096;
static const uint8_t ReferenceSHA256[]{0x07,0x02,0xf8,0x7f,0xdb,0xba,0x22,0xbc,0xbd,0x01,0x48,0x90,0x08,0x26,0xe0,0xc4,0xe3,0xc1,0xf1,0xe9,0xc4,0x5f,0xd2,0x50,0x2f,0x62,0xff,0x70,0xdc,0x94,0x12,0x08};
static constexpr size_t PatchOffset=0xdb7;
static const uint8_t Replacement[] {
 0xb8,0x32,0x35,0x47,0x33,0x33,0x45,0xb0,0xb9,0x33,0x33,0x32,0x00,0x33,0x4d,0xb3,0x09,0xc1,0x75,0xb4
};
static constexpr size_t ArchivePatchOffset=0xaea;
static const uint8_t ArchiveReplacement[] {
 0xb8,0x32,0x35,0x47,0x33,0x33,0x45,0xd0,0xb9,0x33,0x33,0x32,0x00,0x33,0x4d,0xd3,0x09,0xc1,0x75,0xa9
};
static const uint8_t Original[]{0xb8,0x32,0x35,0x47,0x32,0x33,0x45,0xb0,0xb9,0x32,0x34,0x31,0x0,0x33,0x4d,0xb3,0x9,0xc1,0x75,0xb4};
inline bool matches(const void *data,size_t size,uint64_t fileOffset,bool validated,bool tainted) {
 if(!data || size!=PageSize || fileOffset!=0 || !validated || tainted)return false;
 const auto page=static_cast<const uint8_t *>(data);
 // Most pages fail this short check; a match still requires all 4096 bytes.
 return !memcmp(page+PatchOffset,Original,sizeof(Replacement)) &&
        UHD770Page::matches(page,PageSize,ReferenceSHA256);
}
inline void apply(void *data) {
 memcpy(static_cast<uint8_t *>(data)+PatchOffset,Replacement,sizeof(Replacement));
 memcpy(static_cast<uint8_t *>(data)+ArchivePatchOffset,ArchiveReplacement,sizeof(ArchiveReplacement));
}
}
